import test from "node:test";
import assert from "node:assert/strict";
import express from "express";
import { readFile } from "node:fs/promises";
import { supabase } from "../src/config/supabase.js";
import authRoutes from "../src/routes/authRoutes.js";
import rainfallRoutes from "../src/routes/rainfallRoutes.js";
import reportRoutes from "../src/routes/reportRoutes.js";
import sensorRoutes from "../src/routes/sensorRoutes.js";
import recommendationRoutes from "../src/routes/recommendationRoutes.js";
import chatbotRoutes from "../src/routes/chatbotRoutes.js";
import ExcelJS from "exceljs";
import { createOperatorDatabase,USER_A,USER_B,AUTH_A,AUTH_A2 } from "./support/operatorDatabase.js";
import { localSupabaseDatabase } from "./support/localSupabaseDatabase.js";

const fixture=await readFile(new URL("./support/supabaseAuthFunctions.sql",import.meta.url),"utf8");
const secretA="a".repeat(64),secretB="b".repeat(64);
const sensorAcl=db=>db.query(`select relname,relacl::text as acl,relrowsecurity from pg_class
  where oid in ('public.sensors'::regclass,'public.sensor_logs'::regclass,'public.soil_ph_readings'::regclass) order by relname`);

for(const release of ["logout","timeout"]) test(`single-account actual routes: A writes/downloads, B rejected, then B admitted after ${release}`,async()=>{
  let sensorBefore,historicalBefore,server;
  const db=await createOperatorDatabase({beforeMigration:async database=>{
    await database.exec(fixture);
    await database.query("delete from auth.users where id=$1",[USER_B]);
    await database.exec(`alter table public.rainfall_readings alter column id add generated by default as identity(start with 2);
      alter table public.rainfall_readings add column nursery text,add column bedengan int,
        add column unit text default 'mm',add column measured_at timestamptz default clock_timestamp(),
        add column source text,add column created_at timestamptz default clock_timestamp();
      alter table public.audit_logs add column resource_id text,add column ip_address text,
        add column user_agent text,add column created_at timestamptz default clock_timestamp();
      create table public.sensors(id int primary key,sensor_name text,bedengan int,status text,location text);
      create table public.sensor_logs(id int generated always as identity primary key,sensor_id int references public.sensors,
        moisture numeric,temperature numeric,humidity numeric,created_at timestamptz default clock_timestamp());
      create table public.soil_ph_readings(id int generated always as identity primary key,ph_value numeric,
        measured_at timestamptz default clock_timestamp());
      grant select on public.sensors,public.sensor_logs,public.soil_ph_readings to anon,authenticated;
      grant select,insert,update on public.sensors,public.sensor_logs,public.soil_ph_readings to service_role;
      grant usage,select on all sequences in schema public to service_role;
      grant insert on public.audit_logs to service_role;`);
    sensorBefore=(await sensorAcl(database)).rows;
    historicalBefore=(await database.query("select * from public.rainfall_readings where id=1")).rows;
  }});
  const saved={from:supabase.from,rpc:supabase.rpc,getUser:supabase.auth.getUser,getClaims:supabase.auth.getClaims};
  try {
    assert.equal((await db.query("select count(*)::int as n from auth.users")).rows[0].n,1);
    assert.deepEqual((await sensorAcl(db)).rows,sensorBefore);
    assert.deepEqual((await db.query("select * from public.rainfall_readings where id=1")).rows,historicalBefore);
    const adapter=localSupabaseDatabase(db);
    supabase.from=adapter.from; supabase.rpc=adapter.rpc;
    // Local Auth provider stub: both tokens valid, same account, different provider sessions.
    supabase.auth.getUser=async token=>({data:{user:["A","B"].includes(token) ? {id:USER_A,email:"operator@fixture.test"} : null},error:null});
    supabase.auth.getClaims=async token=>({data:{claims:{sub:USER_A,session_id:token==="A" ? AUTH_A : AUTH_A2,exp:Date.now()/1000+3600}},error:null});
    const app=express(); app.use(express.json());
    app.use("/api/auth",authRoutes);app.use("/api/rainfall",rainfallRoutes);
    app.use("/api/reports",reportRoutes);app.use("/api/sensors",sensorRoutes);
    app.use("/api/recommendation",recommendationRoutes);app.use("/api/chatbot",chatbotRoutes);
    app.use((error,_req,res,_next)=>res.status(500).json({message:error.message}));
    server=await new Promise(resolve=>{const listener=app.listen(0,"127.0.0.1",()=>resolve(listener));});
    const request=async(path,{token,secret,method="GET",body}={})=>{
      const response=await fetch(`http://127.0.0.1:${server.address().port}${path}`,{method,headers:{"Content-Type":"application/json",
        ...(token ? {Authorization:`Bearer ${token}`,"X-Session-Id":secret ?? (token==="A" ? secretA : secretB)} : {})},
        ...(body ? {body:JSON.stringify(body)} : {})});
      const bytes=Buffer.from(await response.arrayBuffer());
      const text=bytes.toString("utf8");
      return {status:response.status,bytes,headers:response.headers,
        body:response.headers.get("content-type")?.includes("application/json") ? JSON.parse(text) : text};
    };
    const session=(token,path="session")=>request(`/api/auth/${path}`,{token,method:"POST"});
    const sensor=()=>request("/api/sensors",{method:"POST",body:{sensor1:{kelembaban:55},dht11:{suhu:28,kelembaban_udara:72,valid:true}}});
    const ph=()=>request("/api/sensors/ph",{method:"POST",body:{soil_ph:6.4}});
    const rainfall={rainfall_value:20,unit:"mm",measured_at:new Date().toISOString(),notes:"operator input"};
    const day=new Date().toISOString().slice(0,10);
    const filters={sensorId:1,startDate:day,endDate:day,format:"csv"};
    const lease=async()=>(await db.query("select * from public.global_operator_session")).rows[0];
    const publicChecks=async()=>{
      for(const path of ["/api/rainfall/history","/api/rainfall/latest","/api/rainfall/trend",
        "/api/sensors","/api/sensors/overview","/api/sensors/1/data","/api/sensors/1/recent-logs",
        "/api/sensors/ph","/api/sensors/ph/history"]) assert.equal((await request(path)).status,200,path);
      const recommendation=await request("/api/recommendation/decision?sensorId=1");
      assert.equal(recommendation.status,200);assert.ok(recommendation.body.decision.code);
      assert.ok(recommendation.body.generalRecommendations.length>=3);
      const chat=await request("/api/chatbot",{method:"POST",body:{message:"Buatkan program game sepak bola"}});
      assert.equal(chat.status,200);assert.equal(chat.body.success,true);
      // Without an external AI key, domain questions reach the AI configuration
      // branch (503), never operator authorization (401/409).
      assert.equal((await request("/api/chatbot",{method:"POST",body:{message:"Bagaimana pemupukan bibit kelapa sawit?"}})).status,503);
      const localFetch=globalThis.fetch,localKey=process.env.GEMINI_API_KEY;
      let providerCalls=0;
      try {
        process.env.GEMINI_API_KEY="local-only-test-ai-key";
        globalThis.fetch=async(input,options)=>{
          const url=new URL(typeof input==="string" || input instanceof URL ? input : input.url);
          if(url.hostname==="generativelanguage.googleapis.com") {
            providerCalls+=1;
            return Response.json({candidates:[{content:{role:"model",parts:[{text:"Pantau kondisi media bibit kelapa sawit sebelum pemupukan."}]},finishReason:"STOP"}]});
          }
          return localFetch(input,options);
        };
        const reply=await request("/api/chatbot",{method:"POST",body:{message:"Bagaimana pemupukan bibit kelapa sawit?"}});
        assert.equal(reply.status,200);assert.match(reply.body.reply,/kelapa sawit/);assert.equal(providerCalls,1);
      } finally {globalThis.fetch=localFetch;process.env.GEMINI_API_KEY=localKey;}
    };
    assert.equal((await request("/api/rainfall/history")).status,200);
    assert.equal((await sensor()).status,201);assert.equal((await ph()).status,201);
    assert.equal((await db.query("select count(*)::int as n from public.sensor_logs")).rows[0].n,1);
    assert.equal((await db.query("select count(*)::int as n from public.soil_ph_readings")).rows[0].n,1);
    await publicChecks();
    assert.equal((await session("A")).body.lease.created,true);
    const first=await lease();
    assert.equal(first.expires_at-first.last_active_at,600_000);
    assert.equal((await session("B")).body.lease,undefined);
    const denied=await session("B");assert.equal(denied.status,409);assert.equal(denied.body.code,"GLOBAL_SESSION_BUSY");
    assert.deepEqual(await lease(),first);
    for(const [path,method,body] of [["/api/rainfall","POST",rainfall],["/api/rainfall/1","PATCH",rainfall],
      ...["csv","xlsx","pdf"].map(format=>["/api/reports/download","POST",{...filters,format}])]) {
      assert.equal((await request(path,{method,body})).status,401);
      assert.equal((await request(path,{token:"B",method,body})).status,401);
      assert.equal((await request(path,{token:"B",secret:secretA,method,body})).status,401);
    }
    assert.equal((await session("B","logout")).status,401);
    assert.deepEqual(await lease(),first);
    assert.equal((await db.query("select count(*)::int as n from public.rainfall_readings")).rows[0].n,1);
    const created=await request("/api/rainfall",{token:"A",method:"POST",body:rainfall});
    assert.equal(created.status,201);const id=created.body.reading.id;
    assert.equal((await request(`/api/rainfall/${id}`,{token:"A",method:"PATCH",body:{...rainfall,rainfall_value:25,notes:"operator edit"}})).status,200);
    assert.equal(Number((await db.query("select rainfall_value from public.rainfall_readings where id=$1",[id])).rows[0].rainfall_value),25);
    for(const format of ["csv","xlsx","pdf"]) {
      const download=await request("/api/reports/download",{token:"A",method:"POST",body:{...filters,format}});
      assert.equal(download.status,200);assert.match(download.headers.get("content-disposition"),/attachment/);
      if(format==="csv") assert.match(download.body,/Sensor/);
      if(format==="pdf") assert.equal(download.bytes.subarray(0,5).toString(),"%PDF-");
      if(format==="xlsx") {
        const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(download.bytes);
        assert.equal(workbook.worksheets.length,2);
      }
    }
    // Reload restoration validates the existing session; retry acquisition is idempotent.
    assert.equal((await request("/api/auth/session-status",{token:"A"})).status,200);
    assert.equal((await session("A")).body.lease.created,false);
    assert.deepEqual(await lease(),first);
    assert.equal((await db.query("select count(*)::int as n from public.operator_session_admissions")).rows[0].n,1);
    for(const role of ["anon","authenticated"]) {
      await db.exec(`set role ${role}`);
      try {
        assert.equal((await db.query("select * from public.rainfall_readings")).rows.length,2);
        for(const sql of ["insert into public.rainfall_readings(rainfall_value) values(99)",
          "update public.rainfall_readings set notes='bypass'", "delete from public.rainfall_readings", "truncate public.rainfall_readings"])
          await assert.rejects(db.exec(sql),error=>error.code==="42501");
      } finally {await db.exec("reset role");}
    }
    assert.equal((await sensor()).status,201);assert.equal((await ph()).status,201);
    await publicChecks();
    if(release==="timeout") {
      // Advance stored database timestamps; this is not a 10-minute wall-clock test.
      await db.exec(`update public.global_operator_session set created_at=created_at-interval '10 minutes 1 second',
        last_active_at=last_active_at-interval '10 minutes 1 second',expires_at=expires_at-interval '10 minutes 1 second'`);
      assert.equal((await request("/api/rainfall",{token:"A",method:"POST",body:rainfall})).body.code,"SESSION_TIMEOUT");
    } else assert.equal((await session("A","logout")).body.released,true);
    assert.equal((await session("B")).status,200);
    assert.equal((await lease()).auth_session_id,AUTH_A2);
    assert.equal((await request("/api/rainfall",{token:"B",method:"POST",body:rainfall})).status,201);
    assert.equal((await db.query("select count(*)::int as n from public.audit_logs where action='RAINFALL_CREATE'")).rows[0].n,2);
    assert.equal((await request("/api/rainfall",{token:"A",method:"POST",body:rainfall})).body.code,"SESSION_MISMATCH");
    const rollback=await readFile(new URL("../database/20261008_global_session_rollback.sql",import.meta.url),"utf8");
    const recovery=await readFile(new URL("../database/20261008_global_session_recovery.sql",import.meta.url),"utf8");
    await db.exec(rollback);
    assert.equal((await request("/api/rainfall",{token:"B",method:"POST",body:rainfall})).status,503);
    assert.equal((await request("/api/rainfall/history")).status,200);
    assert.equal((await sensor()).status,201);assert.equal((await ph()).status,201);
    await publicChecks();
    await db.exec(recovery);
    assert.equal((await request("/api/auth/session-status",{token:"B"})).status,200);
    assert.deepEqual((await sensorAcl(db)).rows,sensorBefore);
    assert.deepEqual((await db.query("select * from public.rainfall_readings where id=1")).rows,historicalBefore);
  } finally {
    if(server)await new Promise(resolve=>server.close(resolve));
    supabase.from=saved.from;supabase.rpc=saved.rpc;
    supabase.auth.getUser=saved.getUser;supabase.auth.getClaims=saved.getClaims;
    await db.close();
  }
});
